def said(link=LINK, power="off", station=STATION, ip=IP_LINK, sysfs=SYSFS):
    """What READ gives: the answers of iw, ip and /sys between the echo @@."""
    return f"{link}@@\nPower save: {power}\n@@\n{station}@@\n{ip}\n@@\n{sysfs}"


def test_what_iw_says():
    assert network.parse(said()) == {
        "connected": True, "power_save": False, "ssid": "Werkstatt", "access_point": "02:00:00:aa:bb:cc", "frequency": 2437,
        "channel": 6, "signal": -71.0, "rx_rate": 57.7, "tx_rate": 72.0, "connected_time": 5400, "tx_packets": 14238,
        "tx_retries": 321, "tx_failed": 4}
    # A driver that gives no station dump, rates with more after the number.
    values = network.parse(said(LINK.replace("72.0 MBit/s", "72.2 MBit/s MCS 7 short GI"), "on", ""))
    assert (values["tx_rate"], values["power_save"], values["connected_time"], values["tx_retries"]) == (72.2, True, None, None)
    assert network.parse(said("Not connected.\n", "on", "")) == {"connected": False, "power_save": True}
    # No iw, or no wlan0: nothing known.
    assert network.parse("sh: iw: not found\n@@\n@@\n@@\n@@\n") == {"connected": None, "power_save": None}
    assert [network.channel(f) for f in (2412, 2437, 2472, 2484, 2413, 5180, None)] == [1, 6, 13, 14, None, None, None]


