def test_without_ssh_what_moonraker_says(server, printer, monkeypatch):
    """Root Access off, or neither key nor password fits: the page keeps Moonraker's part and the
    printer's checks; the rest needs SSH. Any other Klipper printer: no SSH at all."""
    closed = socket.create_server(("127.0.0.1", 0))
    monkeypatch.setattr(ssh, "PORT", closed.getsockname()[1])
    closed.close()
    with _open(server) as ws:
        assert _next(ws, "info")["interfaces"]
        answer = _next(ws, "ssh")
        assert (answer["state"], answer["code"]) == ("failed", "ssh_unreachable")
        assert _check(ws, "printer")["state"] == "ok"
        assert _next(ws, "check", lambda m: m["item"] == "router")["state"] == "ssh"
        ws.send(json.dumps({"do": "scan"}))
        assert _next(ws, "failed") == {"type": "failed", "action": "scan", "code": "ssh_needed"}
    camera.set_host("MyKlipper", camera.printers()["Snapmaker U1"]["host"])
    with _open(server, "MyKlipper") as ws:
        assert _next(ws, "ssh") == {"type": "ssh", "state": "none"}
        assert _next(ws, "check", lambda m: m["item"] == "dns")["state"] == "ssh"
    with _open(server, "Unbekannt") as ws:
        assert json.loads(ws.recv(timeout=5)) == {"type": "error", "code": "printer_not_found"}
    # Hard rule 8: only OrcaOne's own page.
    with pytest.raises(InvalidStatus):
        connect(server.replace("http://", "ws://") + "/api/network?model=Snapmaker%20U1", origin="http://evil.example", open_timeout=5)


