def test_from_another_device_no_keys_of_this_computer(server, printer, monkeypatch):
    """As on the page "SSH": from the LAN only the password as shipped, never this computer's keys."""
    monkeypatch.setattr(app_module, "is_remote", lambda client: True)
    tried, real = [], ssh.connect
    monkeypatch.setattr(ssh, "connect", lambda host, user, password=None, key=None: tried.append(password) or real(host, user, password, key))
    ssh.save_setting("Snapmaker U1", None, None, "auto")   # at the computer the keys would come first
    with _open(server) as ws:
        assert (_next(ws, "ssh")["keys"], _next(ws, "values") is not None) == (False, True)
    assert tried == ["snapmaker"]


def test_the_login_as_chosen(server, printer, monkeypatch):
    """As chosen on "SSH" (ssh.login_of): with nothing chosen only the password as shipped, with
    "auto" the keys first; the chosen key is said, so the page warns only when that one failed."""
    tried, real = [], ssh.connect
    monkeypatch.setattr(ssh, "connect", lambda host, user, password=None, key=None: tried.append(password) or real(host, user, password, key))
    for login, expected in ((None, ["snapmaker"]), ("auto", [None, "snapmaker"])):
        tried.clear()
        ssh.save_setting("Snapmaker U1", None, None, login)
        with _open(server) as ws:
            assert _next(ws, "ssh") == {"type": "ssh", "state": "open", "via": "default", "keys": True, "key": None}
        assert tried == expected, login


def test_one_action_at_a_time_is_said(server, printer):
    """While the first checks run, an action is refused with a word, never swallowed: the page would
    wait for it forever."""
    with _open(server) as ws:
        ws.send(json.dumps({"do": "scan"}))
        assert _next(ws, "failed") == {"type": "failed", "action": "scan", "code": "wifi_busy"}


def test_no_restart_while_nobody_knows(monkeypatch):
    """Klipper prints or not, and Moonraker cannot tell: no restart. Klipper not ready: no print."""
    def refused(host, objects):
        raise CameraError("camera_unreachable")
    monkeypatch.setattr(camera, "query", refused)
    klippy = ["ready"]
    monkeypatch.setattr(camera, "_get", lambda host, path: {"klippy_state": klippy[0]})
    with pytest.raises(CameraError) as err:
        network._printing("x")
    assert err.value.code == "wifi_printing_unknown"
    klippy[0] = "shutdown"
    assert network._printing("x") is False
    monkeypatch.setattr(camera, "_get", lambda host, path: (_ for _ in ()).throw(CameraError("camera_unreachable")))
    with pytest.raises(CameraError):
        network._printing("x")
